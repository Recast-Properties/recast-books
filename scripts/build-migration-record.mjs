// Regenerates lib/migration-record.mjs - the migration's record of each document, so the
// nightly check can tell a receipt the migration carries from one on no book (the bundle
// cannot read data/ at runtime). `links`: the migrated rows each document is attached to
// (rows/entries.json). `settled`: documents the migration audit kept off the books with a
// recorded reason (paul-answers.json mail_settled - not differences_settled, whose documents
// are attached to rows and stand or fall with them), the re-post overrides that dismissed a
// document under a D-026 rule (books-repost-*.json: personal ride, a purchase that migrates from
// the Cash Advances tab, a payment that duplicates its bill), and the two the 2026-09-26 audit settled.
// Run: node scripts/build-migration-record.mjs   (a test asserts the two files are in sync)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const LATER = [
  "gm-19e2257005de0d6e", // VistaPrint 405.84 of 05-13: the 05-08 order re-placed on a store credit - the Ashburne Signage row (phase4-audit §36)
  "gm-1a08dc3752960a45", // Uber Eats 143.12 of 09-10: food delivery, not a cost (it names its own dry run as the duplicate)
];

export function buildRecord() {
  const read = (p) => JSON.parse(readFileSync(new URL(`../data/migration/2026-09-17/${p}`, import.meta.url), "utf8"));
  const links = {};
  for (const e of read("rows/entries.json")) if (e.docId) (links[e.docId] ||= []).push(e.txn_id);
  const answers = read("paul-answers.json");
  const ruled = readdirSync(new URL("../data/migration/2026-09-17/", import.meta.url)).filter((f) => /^books-re(post|play)-.*\.json$/.test(f))
    .flatMap((f) => Object.entries(read(f).overrides || {})).filter(([, o]) => o.verdict === "dismiss" && o.note).map(([id]) => id);
  const settled = [...new Set(answers.mail_settled.map((x) => x.docId).filter(Boolean).concat(ruled, LATER))].sort();
  return { links, settled };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const record = buildRecord();
  writeFileSync(new URL("../lib/migration-record.mjs", import.meta.url),
    "// GENERATED by scripts/build-migration-record.mjs from data/migration/2026-09-17 - do not edit by hand.\n" +
    `export const MIGRATION_RECORD = ${JSON.stringify(record)};\n`);
  console.log("wrote lib/migration-record.mjs:", Object.keys(record.links).length, "linked documents,", record.settled.length, "settled");
}
